create or replace function public.owner_cancel_subscription_v2(
  p_subscription_id uuid,
  p_reason text default null
)
returns void
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_before jsonb;
  v_reason text := nullif(trim(coalesce(p_reason,'')),'');
begin
  if auth.uid() is null then
    raise exception 'authentication required';
  end if;

  if not exists (
    select 1
    from public.aura_admins aa
    where aa.user_id=auth.uid()
      and aa.is_active=true
      and aa.role='owner'
  ) then
    raise exception 'owner access required';
  end if;

  select to_jsonb(s)
  into v_before
  from public.subscriptions s
  where s.id=p_subscription_id;

  if v_before is null then
    raise exception 'Assinatura não encontrada';
  end if;

  update public.subscriptions
  set
    status='cancelled',
    current_period_end=coalesce(current_period_end,now()),
    cancelled_at=now(),
    cancelled_by_user_id=auth.uid(),
    admin_note=coalesce(v_reason,admin_note),
    updated_at=now()
  where id=p_subscription_id;

  insert into public.admin_logs(
    actor_user_id,action,entity_type,entity_id,before_data,after_data
  )
  values(
    auth.uid(),
    'subscription_cancelled',
    'subscription',
    p_subscription_id::text,
    v_before,
    jsonb_build_object('reason',v_reason)
  );
end;
$function$;

revoke all on function public.owner_cancel_subscription_v2(uuid,text)
from public,anon;

grant execute on function public.owner_cancel_subscription_v2(uuid,text)
to authenticated;

create or replace function public.owner_plan_history_v1(
  p_limit integer default 250
)
returns table(
  history_id bigint,
  subscription_id uuid,
  event_type text,
  status text,
  plan_id uuid,
  plan_name text,
  monthly_price numeric,
  audience text,
  profile_id uuid,
  profile_name text,
  assignment_source text,
  provider text,
  period_start timestamptz,
  period_end timestamptz,
  unlimited boolean,
  actor_user_id uuid,
  note text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path=''
stable
as $function$
begin
  if auth.uid() is null then
    raise exception 'authentication required';
  end if;

  if not exists (
    select 1
    from public.aura_admins aa
    where aa.user_id=auth.uid()
      and aa.is_active=true
      and aa.role='owner'
  ) then
    raise exception 'owner access required';
  end if;

  return query
  select
    h.id,
    h.subscription_id,
    h.event_type,
    h.status,
    h.plan_id,
    p.name,
    p.monthly_price,
    case when h.artist_id is not null
      then 'artist'::text
      else 'venue'::text
    end,
    coalesce(h.artist_id,h.venue_id),
    coalesce(a.stage_name,v.trade_name,'Perfil removido'),
    h.assignment_source,
    h.provider,
    h.period_start,
    h.period_end,
    h.unlimited,
    h.actor_user_id,
    h.note,
    h.created_at
  from public.subscription_history h
  left join public.plans p on p.id=h.plan_id
  left join public.artist_profiles a on a.id=h.artist_id
  left join public.venue_profiles v on v.id=h.venue_id
  order by h.created_at desc
  limit greatest(1,least(coalesce(p_limit,250),500));
end;
$function$;

revoke all on function public.owner_plan_history_v1(integer)
